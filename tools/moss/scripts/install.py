#!/usr/bin/env python3
"""Install a built moss executable and its agent integration.

Copies files only; it never edits PATH or any shell profile. Use explicit
paths so the result is reproducible:

  # Install as an agent skill: the binary is bundled in <skill-dir>/moss/bin.
  python scripts/install.py --binary target/release/moss.app/build-1/moss.exe \\
      --skill-dir ~/.claude/skills

  # Optionally also install on PATH:   --prefix ~/.moss

  # Agents without skills (Codex AGENTS.md, Copilot instructions): append a
  # marked section generated from skills/moss/SKILL.md, refreshed on rerun:
  python scripts/install.py --binary ... --prefix ~/.moss \\
      --agent-instructions path/to/repo/AGENTS.md
"""
import argparse
import os
import shutil
import sys

BEGIN = "<!-- moss:begin (generated by moss scripts/install.py; edits are overwritten) -->"
END = "<!-- moss:end -->"
BUNDLED_NOTE = (
    "This skill bundles the executable at\n"
    "`bin/moss` (`bin/moss.exe` on Windows) next to this file; run that path, or\n"
    "plain `moss` if it is on `PATH`."
)


def skill_path():
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.normpath(os.path.join(here, "..", "skills", "moss"))


def write_instructions(path, binary_path):
    with open(os.path.join(skill_path(), "SKILL.md"), encoding="utf-8") as handle:
        text = handle.read().replace("\r\n", "\n")
    body = text.split("---", 2)[2].strip()  # drop the skill front matter
    if binary_path:
        body = body.replace(
            BUNDLED_NOTE,
            "The executable is installed at `" + binary_path + "`; run that path, or plain `moss` if it is on `PATH`.",
        )
    else:
        body = body.replace(BUNDLED_NOTE, "Run `moss` from `PATH`.")
    section = BEGIN + "\n" + body + "\n" + END + "\n"
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8", newline="") as handle:
            existing = handle.read().replace("\r\n", "\n")
    if BEGIN in existing and END in existing:
        head, rest = existing.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        updated = head + section + ("\n" + tail if tail else "")
    else:
        separator = "\n" if existing and not existing.endswith("\n\n") else ""
        updated = existing + separator + section
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(updated)
    print(f"updated agent instructions {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--binary", required=True, help="built moss executable")
    parser.add_argument("--prefix", help="optional install root; the binary goes to <prefix>/bin")
    parser.add_argument("--skill-dir", help="agent skills directory; skills/moss is copied into it")
    parser.add_argument("--agent-instructions",
                        help="AGENTS.md / copilot-instructions.md to append or refresh a marked Moss section in")
    args = parser.parse_args()

    binary = os.path.abspath(args.binary)
    if not os.path.isfile(binary):
        sys.exit(f"install: binary not found: {binary}")
    if not (args.prefix or args.skill_dir or args.agent_instructions):
        sys.exit("install: give --skill-dir, --prefix, or --agent-instructions")
    name = "moss.exe" if os.name == "nt" else "moss"
    installed = None

    if args.prefix:
        bin_dir = os.path.join(os.path.abspath(os.path.expanduser(args.prefix)), "bin")
        os.makedirs(bin_dir, exist_ok=True)
        installed = os.path.join(bin_dir, name)
        shutil.copyfile(binary, installed)
        if os.name != "nt":
            os.chmod(installed, 0o755)
        print(f"installed {installed}")
        paths = os.environ.get("PATH", "").split(os.pathsep)
        if not any(os.path.normcase(os.path.abspath(p)) == os.path.normcase(bin_dir) for p in paths if p):
            print(f"note: {bin_dir} is not on PATH; add it to run `moss` without the skill")

    if args.skill_dir:
        destination = os.path.join(os.path.abspath(os.path.expanduser(args.skill_dir)), "moss")
        shutil.copytree(skill_path(), destination, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns("bin"))
        skill_bin = os.path.join(destination, "bin")
        os.makedirs(skill_bin, exist_ok=True)
        bundled = os.path.join(skill_bin, name)
        shutil.copyfile(binary, bundled)
        if os.name != "nt":
            os.chmod(bundled, 0o755)
        print(f"installed skill {destination} (bundled {bundled})")

    if args.agent_instructions:
        write_instructions(os.path.abspath(os.path.expanduser(args.agent_instructions)), installed)


if __name__ == "__main__":
    main()
